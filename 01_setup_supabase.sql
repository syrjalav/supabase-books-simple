create table if not exists public.books (
    id bigint generated by default as identity primary key,
    upc text not null unique,
    name text not null,
    price_pence integer not null
        check (price_pence >= 0),
    currency text not null default 'GBP',
    stock_count integer
        check (stock_count >= 0),
    rating smallint
        check (rating between 1 and 5),
    category text,
    first_scraped_at timestamptz not null default now(),
    last_scraped_at timestamptz not null default now()
);

create index if not exists books_name_idx
    on public.books (name);

create index if not exists books_category_idx
    on public.books (category);

-- The external scraper uses a trusted direct PostgreSQL connection.
-- Browser/anonymous access is deliberately disabled.
alter table public.books enable row level security;
revoke all on table public.books from anon, authenticated;

comment on table public.books is
    'Books collected from books.toscrape.com by the external Python scraper.';

-- Supabase SQL Editor will display this result when setup succeeds.
select
    'ready' as status,
    count(*)::integer as existing_book_rows
from public.books;
